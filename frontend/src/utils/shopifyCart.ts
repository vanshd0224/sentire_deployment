export const ENGRAVING_FEE_VARIANT_ID = "46947691659425";

export const prepareShopifyCheckoutItems = (rawItems: any[]) => {
  const expanded: any[] = [];
  let engravingCount = 0;

  rawItems.forEach((item) => {
    expanded.push(item);
    if (item.isPersonalised || item.engravingText) {
      engravingCount += (item.quantity || 1);
    }
  });

  if (engravingCount > 0) {
    expanded.push({
      id: "custom-bottle-engraving",
      productId: "custom-bottle-engraving",
      name: "Custom Bottle Engraving",
      size: 0,
      price: 200,
      quantity: engravingCount,
      variantId: ENGRAVING_FEE_VARIANT_ID,
    });
  }

  return expanded;
};

export const resolveShopifyVariantId = (item: any): string => {
  if (item?.variantId) {
    return item.variantId;
  }

  const pId = String(item?.productId || item?.id || "").toLowerCase().trim();
  const pName = String(item?.name || "").toLowerCase().trim();
  const sizeNum = parseInt(String(item?.size || "").replace(/\D/g, ""), 10) || 50;

  if (pId.includes("engraving") || pName.includes("engraving")) {
    return ENGRAVING_FEE_VARIANT_ID;
  }

  if (pId.includes("discovery") || pName.includes("discovery")) {
    return "46965136031905";
  }

  const normalizedId = pId.replace(/[\s\-_]/g, "");
  const normalizedName = pName.replace(/[\s\-_]/g, "");

  if (SHOPIFY_VARIANT_MAP[pId]?.[sizeNum]) {
    return SHOPIFY_VARIANT_MAP[pId][sizeNum];
  }

  for (const [key, sizeMap] of Object.entries(SHOPIFY_VARIANT_MAP)) {
    const normKey = key.replace(/[\s\-_]/g, "");
    if (normalizedName.includes(normKey) || normalizedId.includes(normKey)) {
      if (sizeMap[sizeNum]) return sizeMap[sizeNum];
    }
  }

  // Size-matched fallback (avoids defaulting to 50ML Purple Oud for 10ML/30ML items)
  if (sizeNum === 10) return "46888622293153"; // 10ML variant
  if (sizeNum === 30) return "46888622325921"; // 30ML variant
  return "46888622358689"; // 50ML variant
};

// Shopify Storefront GraphQL cartCreate / cartLinesAdd mutation caller
export const syncAddToCartToShopifyStorefront = async (item: any, quantity: number = 1) => {
  try {
    // Fire Meta Pixel + GA4 AddToCart Event
    try {
      trackAddToCart({
        id: item.productId || item.id || "perfume-1",
        name: item.name || "Luxury Extrait de Parfum",
        price: item.price || 1489,
        quantity: quantity || 1,
        variant: item.size || 50,
      });
    } catch (err) {}

    const shopDomain = "hbj1d0-99.myshopify.com";
    const graphqlUrl = `https://${shopDomain}/api/2026-07/graphql.json`;
    const numericVariantId = resolveShopifyVariantId(item);
    const merchandiseId = `gid://shopify/ProductVariant/${numericVariantId}`;

    const existingCartId = localStorage.getItem("shopify_cart_id");

    const storefrontToken = (import.meta.env && import.meta.env.VITE_SHOPIFY_STOREFRONT_TOKEN) || "";
    const headers: Record<string, string> = { "Content-Type": "application/json" };
    if (storefrontToken) {
      headers["X-Shopify-Storefront-Access-Token"] = storefrontToken;
    }

    const lines: any[] = [{ merchandiseId, quantity }];
    if (item?.isPersonalised || item?.engravingText) {
      lines.push({
        merchandiseId: `gid://shopify/ProductVariant/${ENGRAVING_FEE_VARIANT_ID}`,
        quantity
      });
    }

    if (!existingCartId) {
      // 1. Create new cart with cartCreate mutation
      const mutation = `
        mutation cartCreate($input: CartInput!) {
          cartCreate(input: $input) {
            cart {
              id
              checkoutUrl
            }
            userErrors {
              field
              message
            }
          }
        }
      `;

      const variables = {
        input: {
          lines
        }
      };

      const res = await fetch(graphqlUrl, {
        method: "POST",
        headers,
        body: JSON.stringify({ query: mutation, variables })
      });

      const data = await res.json();
      const newCart = data?.data?.cartCreate?.cart;
      if (newCart?.id && newCart?.checkoutUrl) {
        localStorage.setItem("shopify_cart_id", newCart.id);
        localStorage.setItem("shopify_checkout_url", newCart.checkoutUrl);
        console.log("Shopify Storefront cartCreate Success:", newCart);
      }
    } else {
      // 2. Add lines to existing cart with cartLinesAdd mutation
      const mutation = `
        mutation cartLinesAdd($cartId: ID!, $lines: [CartLineInput!]!) {
          cartLinesAdd(cartId: $cartId, lines: $lines) {
            cart {
              id
              checkoutUrl
            }
            userErrors {
              field
              message
            }
          }
        }
      `;

      const variables = {
        cartId: existingCartId,
        lines
      };

      const res = await fetch(graphqlUrl, {
        method: "POST",
        headers,
        body: JSON.stringify({ query: mutation, variables })
      });

      const data = await res.json();
      const updatedCart = data?.data?.cartLinesAdd?.cart;
      const userErrors = data?.data?.cartLinesAdd?.userErrors || [];

      if (updatedCart?.checkoutUrl) {
        localStorage.setItem("shopify_checkout_url", updatedCart.checkoutUrl);
        console.log("Shopify Storefront cartLinesAdd Success:", updatedCart);
      } else if (userErrors.length > 0 || !updatedCart) {
        // Stale or invalid Cart ID recovery: Clear stale ID and create new cart
        console.warn("Stale Shopify Cart ID detected. Creating fresh cart...", userErrors);
        localStorage.removeItem("shopify_cart_id");
        localStorage.removeItem("shopify_checkout_url");

        // Re-call cartCreate
        const createMutation = `
          mutation cartCreate($input: CartInput!) {
            cartCreate(input: $input) {
              cart { id checkoutUrl }
              userErrors { field message }
            }
          }
        `;
        const createRes = await fetch(graphqlUrl, {
          method: "POST",
          headers,
          body: JSON.stringify({
            query: createMutation,
            variables: { input: { lines } }
          })
        });
        const createData = await createRes.json();
        const freshCart = createData?.data?.cartCreate?.cart;
        if (freshCart?.id && freshCart?.checkoutUrl) {
          localStorage.setItem("shopify_cart_id", freshCart.id);
          localStorage.setItem("shopify_checkout_url", freshCart.checkoutUrl);
          console.log("Shopify Storefront Cart Recovery Success:", freshCart);
        }
      }
    }
  } catch (e) {
    console.log("Shopify Storefront Sync Notice:", e);
  }
};

// Option A: Native HTML Form POST Checkout redirect supporting multi-item, multi-quantity, multi-variant carts
export const redirectToShopifyFormCheckout = (rawItems: any[]) => {
  if (!rawItems || rawItems.length === 0) return;

  const items = prepareShopifyCheckoutItems(rawItems);

  // Track Meta Pixel InitiateCheckout Event
  try {
    const totalVal = items.reduce((acc, curr) => acc + (curr.price * (curr.quantity || 1)), 0);
    trackInitiateCheckout(
      items.map((i) => ({ id: i.productId || i.id, name: i.name, price: i.price, quantity: i.quantity || 1 })),
      totalVal
    );
  } catch (e) {}

  const shopDomain = "hbj1d0-99.myshopify.com";
  const form = document.createElement("form");
  form.method = "POST";
  form.action = `https://${shopDomain}/cart/add`;
  form.style.display = "none";

  items.forEach((item, index) => {
    const variantId = resolveShopifyVariantId(item);
    const qty = Number(item.quantity) || 1;

    const idInput = document.createElement("input");
    idInput.type = "hidden";
    idInput.name = `items[${index}][id]`;
    idInput.value = variantId;
    form.appendChild(idInput);

    const qtyInput = document.createElement("input");
    qtyInput.type = "hidden";
    qtyInput.name = `items[${index}][quantity]`;
    qtyInput.value = String(qty);
    form.appendChild(qtyInput);
  });

  const returnToInput = document.createElement("input");
  returnToInput.type = "hidden";
  returnToInput.name = "return_to";
  returnToInput.value = "/checkout";
  form.appendChild(returnToInput);

  document.body.appendChild(form);
  console.log("[Option A Checkout] Submitting Native Multi-Item Form POST to Shopify...");
  form.submit();
};

// Asynchronously create a fresh GraphQL Shopify Cart via direct Storefront API or permalink fallback
export const createOrGetShopifyCheckoutUrl = async (rawItems: any[], discountCode?: string): Promise<string> => {
  if (!rawItems || rawItems.length === 0) return "";

  const items = prepareShopifyCheckoutItems(rawItems);

  // Track Meta Pixel InitiateCheckout Event
  try {
    const totalVal = items.reduce((acc, curr) => acc + (curr.price * (curr.quantity || 1)), 0);
    trackInitiateCheckout(
      items.map((i) => ({ id: i.productId || i.id, name: i.name, price: i.price, quantity: i.quantity || 1 })),
      totalVal
    );
  } catch (e) {}

  const shopDomain = "hbj1d0-99.myshopify.com";
  const graphqlUrl = `https://${shopDomain}/api/2026-07/graphql.json`;

  const lines = items.map((item) => ({
    merchandiseId: `gid://shopify/ProductVariant/${resolveShopifyVariantId(item)}`,
    quantity: Number(item.quantity) || 1
  }));

  const input: any = { lines };
  if (discountCode) {
    input.discountCodes = [discountCode];
  }

  const storefrontToken = (import.meta.env && import.meta.env.VITE_SHOPIFY_STOREFRONT_TOKEN) || "";
  const headers: Record<string, string> = { "Content-Type": "application/json" };
  if (storefrontToken) {
    headers["X-Shopify-Storefront-Access-Token"] = storefrontToken;
  }

  try {
    const mutation = `
      mutation cartCreate($input: CartInput!) {
        cartCreate(input: $input) {
          cart {
            id
            checkoutUrl
          }
          userErrors {
            field
            message
          }
        }
      }
    `;

    const res = await fetch(graphqlUrl, {
      method: "POST",
      headers,
      body: JSON.stringify({ query: mutation, variables: { input } })
    });

    const data = await res.json();
    const cart = data?.data?.cartCreate?.cart;
    if (cart?.checkoutUrl) {
      let finalUrl = cart.checkoutUrl;
      if (discountCode && !finalUrl.includes("discount=")) {
        finalUrl += (finalUrl.includes("?") ? "&" : "?") + `discount=${encodeURIComponent(discountCode)}`;
      }
      console.log("[Direct Storefront Checkout Success]:", finalUrl);
      return finalUrl;
    }
  } catch (err) {
    console.error("Direct Storefront cartCreate Error:", err);
  }

  // Fast Fallback to Permalink URL
  const permalinkItems = items
    .map((item) => `${resolveShopifyVariantId(item)}:${item.quantity || 1}`)
    .join(",");
  let permalinkUrl = `https://${shopDomain}/cart/${permalinkItems}`;
  if (discountCode) {
    permalinkUrl += (permalinkUrl.includes("?") ? "&" : "?") + `discount=${encodeURIComponent(discountCode)}`;
  }
  return permalinkUrl;
};

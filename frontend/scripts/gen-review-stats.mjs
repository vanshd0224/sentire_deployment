// Precomputes each perfume's review summary (count, average, star breakdown)
// into src/data/reviewStats.ts, so code that runs on every page (the SEO
// schema) doesn't have to ship all of reviews.ts (~400 KB) just to count.
//
// Run after editing src/data/reviews.ts:  node scripts/gen-review-stats.mjs
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = await build({
  entryPoints: [path.join(root, "src/data/reviews.ts")],
  bundle: true,
  format: "esm",
  write: false,
  platform: "neutral",
});
const mod = await import("data:text/javascript;base64," + Buffer.from(out.outputFiles[0].text).toString("base64"));

const stats = {};
for (const id of Object.keys(mod.PERFUME_REVIEWS)) stats[id] = mod.getPerfumeReviewStats(id);

writeFileSync(
  path.join(root, "src/data/reviewStats.ts"),
  `// Generated by scripts/gen-review-stats.mjs from reviews.ts — do not edit.
import type { PerfumeReviewStats } from "./reviews";

export const REVIEW_STATS: Record<string, PerfumeReviewStats> = ${JSON.stringify(stats, null, 2)};

const NONE: PerfumeReviewStats = {
  count: 0,
  averageRating: 5.0,
  ratingBreakdown: { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 },
};

/** A perfume's review summary, without loading the reviews themselves. */
export const getReviewStats = (productId: string): PerfumeReviewStats =>
  REVIEW_STATS[productId] ?? NONE;
`,
);
console.log("wrote reviewStats.ts for", Object.keys(stats).length, "perfumes");
